/**
 * Properties of the bitrate-under-loss tool that single fixtures cannot pin.
 *
 *   pnpm test
 *
 *  - it is the demo: the rate chart equals `backoff_sim.py --csv` second by second, for both scenarios at both of
 *    the demo's report intervals;
 *  - the rule as the draft states it, at the thresholds: 5/256 grows, 6/256 and 25/256 hold, 26/256 cuts;
 *  - the codec's limits: never below 6 kb/s of Opus or above the ceiling, for every input combination tried;
 *  - the sender grows only on a report below 2%, and shrinks only on one above 10%;
 *  - the reported fraction is RFC 3550's truncation of the loss in its interval, never a rounding up;
 *  - loss the sender did not cause is lost whatever it does: the radio link loses 200 packets at every interval;
 *  - recovery is counted in reports: 9 increases of 5% from 32.28 to 48 kb/s, so 9 report intervals.
 */
import assert from "node:assert/strict";
